"""Existing canonical suites plus character contracts, with writable cloud dirs.

Reports generated by prior motion tests are copied into this milestone's evidence;
the tracked historical files are then restored, never mixed with current reports.
"""
import json
import os
from pathlib import Path
import subprocess
import time

base = Path(__file__).resolve().parents[1]
out = base / os.environ.get('CHROMA_REGRESSION_OUT','evidence/run-lifecycle/regression')
out.mkdir(parents=True, exist_ok=True)
env = dict(os.environ)
for key, value in {'XDG_DATA_HOME':'/tmp/chroma-tools/data', 'XDG_CONFIG_HOME':'/tmp/chroma-tools/config', 'XDG_CACHE_HOME':'/tmp/chroma-tools/cache'}.items():
    env[key] = value
commands = json.loads((base/'evidence/impact/final-regression/results.json').read_text())
commands += [{'test':name, 'command':['--headless','--path',str(base),'--script',f'tests/{name}.gd']} for name in ['test_characters','test_character_input','test_character_interactions','test_area_session','test_area_input','test_area_transactions','test_bombs','test_bomb_scene','test_impact_strength','test_bomb_body','test_bomb_volume','test_bomb_support','test_colored_bombs','test_impact_focus']]
results = []
for row in commands:
    name = row['test']
    args = row['command'][:]
    args[args.index('--path')+1] = str(base)
    if not name.startswith('test_area_') and name not in ['test_bombs','test_bomb_scene','test_impact_strength','test_bomb_body','test_bomb_volume','test_bomb_support','test_colored_bombs','test_impact_focus']:
        if '--' not in args: args += ['--']
        args += ['--short-run']
    if '--' not in args: args += ['--']
    args += ['--seed=20261021', '--no-save']
    started = time.monotonic()
    try:
        run = subprocess.run(['godot', *args], cwd=base, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=50)
        code, log = run.returncode, run.stdout
    except subprocess.TimeoutExpired as error:
        code = 124
        log = (error.stdout or b'').decode() if isinstance(error.stdout, bytes) else error.stdout or ''
    (out/f'{name}.log').write_text(log)
    errors = [line for line in log.splitlines() if 'ERROR' in line or line.startswith('FAIL') or 'Assertion failed' in line]
    results.append({'test':name, 'exit':code, 'errors':errors, 'wall_seconds':round(time.monotonic()-started,3), 'command':args})
    (out/'results.json').write_text(json.dumps(results, indent=2))
    print(name, code, errors[:2], flush=True)
# These test-owned files existed at task start; retain fresh copies separately.
preserved = base/os.environ.get('CHROMA_MOTION_OUT','evidence/run-lifecycle/new-motion-regressions')
preserved.mkdir(exist_ok=True)
for relative in ['evidence/growth/inlet-green.json', 'evidence/motion-fix/path-traces.json', 'evidence/refill-stall/exact-green.json', 'evidence/refill-stall/exact-green.var', 'evidence/impact-strength/bomb-supply-path.json','evidence/bomb-volume/dense-trace.json','evidence/bomb-volume/support-traces.json']:
    target = base/relative
    (preserved/target.name).write_bytes(target.read_bytes())
    original = subprocess.check_output(['git','show','HEAD:agent-harness/prototypes/godot-touch-board/'+relative], cwd=base)
    target.write_bytes(original)
failed = sum(row['exit'] != 0 or bool(row['errors']) for row in results)
print('CORE',len(results),'FAILURES',failed)
raise SystemExit(bool(failed))
